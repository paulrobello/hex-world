"""The shots manifest (`scripts/shots/targets.json`, docs/agent-operability.md, Make targets).

One row per checkpoint target that follows the shared recipe: `make shots-<name>` (the
Makefile's pattern rule) builds `hex-app` once and runs `scripts/shots/piece.py` once per
entry of `runs`. An irregular target (multi-step water, photo, boids, scatter, web
captures) keeps its explicit Makefile rule and stays out of the manifest.

`--commands <name> [extra...]` prints the shell lines the pattern rule runs, so `make -n
shots-<name>` shows the resolved captures; on an unknown name or a bad manifest it prints
a shell line that reports the error and exits 2. `--markdown` prints the doc table for
`docs/agent-operability.md`; the block between the markers there is generated and a
`make shots-test` case fails when it is stale.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import shlex
import sys

MANIFEST = pathlib.Path(__file__).with_name("targets.json")
REPO = MANIFEST.parent.parent.parent
DOC = REPO / "docs" / "agent-operability.md"
DOC_BEGIN = "<!-- shots-targets:begin (generated by scripts/shots/targets.py --markdown; do not edit by hand) -->"
DOC_END = "<!-- shots-targets:end -->"
DEFAULT_SIZE = "1600x1000"
RUNNER = "python3 scripts/shots/piece.py"


def load() -> list[dict]:
    """The manifest rows, with each run's shape checked. Raises ValueError on a bad row
    or a duplicate name, so a typo fails every consumer loudly."""
    rows = json.loads(MANIFEST.read_text())
    names: set[str] = set()
    for row in rows:
        name = row.get("name", "")
        if not name or not row.get("about") or not row.get("doc"):
            raise ValueError(f"manifest row needs name, about and doc: {row!r}")
        if name in names:
            raise ValueError(f"duplicate manifest name {name}")
        names.add(name)
        runs = row.get("runs")
        if not runs:
            raise ValueError(f"{name}: runs is empty")
        for run in runs:
            if not run.get("script") or not run.get("out"):
                raise ValueError(f"{name}: every run needs script and out: {run!r}")
            size = run.get("size")
            if size is not None and (
                not isinstance(size, str)
                or len(parts := size.split("x")) != 2
                or not all(p.isdigit() for p in parts)
            ):
                raise ValueError(f"{name}: size must be WxH, got {size!r}")
            args = run.get("args", "")
            if not isinstance(args, str):
                raise ValueError(f"{name}: args must be one string, got {args!r}")
    return rows


def by_name() -> dict[str, dict]:
    return {row["name"]: row for row in load()}


def piece_args(run: dict, extra: list[str]) -> list[str]:
    """piece.py's argv for one run: the shared source for the runner (target.py) and the
    printed commands, so the two cannot drift. Size is passed only when the row carries
    one; otherwise piece.py's own 1600x1000 default holds."""
    argv = ["--script", run["script"], "--out", run["out"]]
    if "size" in run:
        argv += ["--size", run["size"]]
    return argv + ["--", *run.get("args", "").split(), *extra]


def commands(name: str, extra: list[str]) -> str:
    """The shell line for `make shots-<name>`: one release build, then piece.py per run,
    chained with && so make stops at the first failure. Make flattens $(shell) output
    newlines to spaces in a recipe, so the line is joined, never multi-line. Never raises:
    any failure becomes a shell line that reports it and exits 2, so the pattern rule
    cannot silently run nothing."""
    try:
        row = by_name()[name]
    except ValueError as e:
        return f'printf \'%s\\n\' "{_plain(str(e))}"; exit 2'
    except KeyError:
        known = ", ".join(by_name())
        return f'printf \'%s\\n\' "unknown shots target {name} (known: {known})"; exit 2'
    parts = ["cargo build -p hex-app --release"]
    parts += [RUNNER + " " + shlex.join(piece_args(run, extra)) for run in row["runs"]]
    return " && ".join(parts)


def _plain(text: str) -> str:
    """Strip the quotes a printf or shlex would otherwise misread."""
    return text.replace('"', "").replace("'", "")


def markdown() -> str:
    """The generated doc table, header included."""
    rows = load()
    lines = ["| Target | What it does |", "|---|---|"]
    lines += [f'| `make shots-{r["name"]}` | {r["doc"]} |' for r in rows]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("name", nargs="?")
    ap.add_argument("extra", nargs="*", help="hex-world flags appended to every run")
    ap.add_argument("--commands", action="store_true", help="print the shell lines for make")
    ap.add_argument("--markdown", action="store_true", help="print the doc table rows")
    a = ap.parse_args(argv)
    try:
        if a.markdown:
            print(markdown())
            return 0
        if a.commands and a.name:
            print(commands(a.name, a.extra))
            return 0
    except Exception as e:  # the make recipe runs this in $(shell): stdout must never be empty,
        # or make would silently run nothing
        print(f'printf \'%s\\n\' "{_plain(f"{type(e).__name__}: {e}")}"; exit 2')
        return 0
    ap.error("nothing to do: pass --commands <name> or --markdown")
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
