"""Writes the 12 `data/tiles/hillside_<pattern>.ron` files (P4 elevation), deterministically.

A hillside is a meadow whose six corners sit at relative height 0 or 1. The 12 patterns are the
binary necklaces of length 6 (all-0 and all-1 excluded), each named by its lexicographically
smallest rotation read as corners c0..c5. Edge `e` runs from corner (e + 5) % 6 to corner e
(`hex_core::edge_corners`): (0,0) is Flat h0, (1,1) Flat h1, (0,1) Rise h0, (1,0) Fall h0.
The scatter list is meadow's, copied from `data/tiles/meadow.ron`.

Run: uv run scripts/tiles/hillsides.py
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TILES = ROOT / "data" / "tiles"


def necklaces() -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for n in range(1, 63):
        bits = format(n, "06b")
        canon = min(bits[i:] + bits[:i] for i in range(6))
        if canon not in seen:
            seen.add(canon)
            out.append(canon)
    return sorted(out)


def edge_ron(start: int, end: int) -> str:
    if start == end:
        return f"(kind: Grass, height: {start})" if start else "(kind: Grass)"
    if start == 0:
        return "(kind: Grass, profile: Rise)"
    return "(kind: Grass, profile: Fall)"


def meadow_scatter() -> str:
    text = (TILES / "meadow.ron").read_text()
    m = re.search(r"scatter: \[\n(.*?)\n        \],", text, re.S)
    assert m, "meadow.ron scatter list not found"
    return m.group(1)


def render(pattern: str, scatter: str) -> str:
    c = [int(b) for b in pattern]
    edges = "\n".join(f"        {edge_ron(c[(e + 5) % 6], c[e])}," for e in range(6))
    return f"""// Hillside {pattern} (P4): meadow ground with corner heights c0..c5 = {pattern}, edge e running
// from corner (e + 5) % 6 to corner e. Generated by scripts/tiles/hillsides.py: edit that, not this.
(
    id: "hillside_{pattern}",
    biome: Grass,
    base: "meadow_base",
    edges: (
{edges}
    ),
    props: (
        scatter: [
{scatter}
        ],
    ),
    raisable: true,
)
"""


def main() -> None:
    pats = necklaces()
    assert len(pats) == 12, pats
    scatter = meadow_scatter()
    for p in pats:
        (TILES / f"hillside_{p}.ron").write_text(render(p, scatter))
    print(" ".join(pats))


if __name__ == "__main__":
    main()
